"""Interaction Agent - 선택지 질문을 버튼으로도 답할 수 있게 하는 범용 도구.

원래 "소유자이신가요, 임차인이신가요?" 질문 하나만 PROCEDURE_TREE의 branch
노드에 하드코딩돼 있었고, 그 노드에 도달했을 때만(set_procedure_stage 합성
tool_call) 사이드바에 별도 버튼 박스가 떴다. 이 방식은 확장이 안 됐다 -
새로운 선택형 질문을 추가하려면 매번 트리 구조를 손봐야 했고, 버튼도 채팅
말풍선과 분리된 위치(사이드바)에 있어서 대화 흐름과 따로 놀았다(2026-07-28
피드백: "그 위치에서는 삭제하고, 필요하면 버튼으로 답할 수 있게").

여기서는 반대로 접근한다 - LLM이 대화 중 "정해진 선택지 중 하나로 답해야
하는" 질문을 할 때마다(소유자/임차인뿐 아니라 앞으로 생길 다른 질문도)
이 도구를 답변 텍스트와 같은 턴에 함께 호출하게 한다. 도구 자체는 상태를
기록하지 않는다(순수 UI 힌트) - question/options는 그대로 프론트엔드에
tool_calls로 전달되고, 프론트가 봇 말풍선 바로 아래에 버튼으로 렌더링한다.
사용자가 버튼을 누르면 그 선택지 텍스트가 그대로 다음 사용자 메시지로
전송되므로, 그 다음은 기존 텍스트 답변 처리 경로(record_case_facts 등)와
완전히 동일하게 흘러간다 - 새로운 상태 채널이 생기지 않는다.
"""
from __future__ import annotations

import logging

from langchain_core.tools import tool

logger = logging.getLogger(__name__)


@tool
def ask_choice(question: str, options: list[str]) -> str:
    """정해진 선택지 중 하나로만 답할 수 있는 질문을 할 때, 답변 텍스트에 그
    질문을 쓰는 것과 별개로 이 도구도 같은 턴에 함께 호출하세요.

    - 예: "소유자이신가요, 임차인이신가요?" → ask_choice("소유 여부", ["소유자", "임차인"]).
    - 사용자가 자유 텍스트로 답해야 하는 질문(면적이 몇 ㎡인지 등)에는
      호출하지 마세요 - 선택지가 2~5개 정도로 명확히 나뉠 때만 쓰세요.
    - 이 도구는 상태를 기록하지 않습니다 - 사용자가 버튼을 누르면 그 선택지
      텍스트가 일반 사용자 메시지로 그대로 전송되니, record_case_facts 등
      실제 기록은 평소처럼 다음 턴에 답변 텍스트를 보고 하세요.

    Args:
        question: 선택지 질문의 짧은 요약(버튼 그룹 위 라벨로 쓰일 수 있음)
        options: 버튼으로 보여줄 선택지 목록(2~5개 권장)
    """
    logger.info("[도구] ask_choice(%r, %r)", question, options)
    return "선택지가 버튼으로 표시됩니다."
