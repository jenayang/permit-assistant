"""Opening Checklist Agent - 오픈 준비(Step 4) 안내(부분 RAG 전환).

인테리어ᆞ장비 설치는 원래 여기 있었는데, 실제로는 "시공"의 일부라 공사
단계(construction.py, Step 2)로 옮겼다(2026-07-28 피드백 - 로드맵에서도
Step 2 안으로 이동). 이 모듈에는 진짜 "오픈 준비"(공사가 다 끝난 뒤, 영업
시작 직전에 하는 일)만 남는다:
- 직원 등록(4대보험 가입): 실제 신고 기한이 법령으로 정해진 행정 절차라
  RAG 전환 대상이다. 원래는 "법제처 찾기쉬운 생활법령정보"(2차 출처)
  원문 대조로 하드코딩했었는데, 2026-07-28에 국민연금법ᆞ국민건강보험법ᆞ
  고용보험법ᆞ고용산재보험료징수법(1차 출처) 원문을 새로 인덱싱한 뒤
  RAG로 검증하니 4개 법령의 신고 조항을 정확히 다 찾아내서(제8조ᆞ21조ᆞ
  15조ᆞ11조) 하드코딩 대신 검색으로 전환했다.
- 영업 시작: 법령 근거가 있는 게 아니라 순수 체크리스트라 정적 텍스트로
  유지(검색할 조항 자체가 없음, [출처] 지어내지 않음).
"""
from __future__ import annotations

import logging

from langchain_core.tools import tool

from src.rag.regulation import search_regulations

logger = logging.getLogger(__name__)


OPENING_CHECKLIST_STATIC = """[오픈 준비 체크리스트]

공사(인테리어ᆞ장비 설치 포함)가 끝난 뒤, 영업을 시작하기 직전에 확인할
항목입니다. 인테리어ᆞ장비 설치 관련 안내는 공사 단계(착공신고ᆞ시공 등)와
함께 확인하실 수 있습니다.

2. 영업 시작
   - 지금까지 안내받은 단계(건축 인허가ᆞ공사ᆞ식품위생 영업신고ᆞ소방시설ᆞ
     사업자등록ᆞ위생교육ᆞ직원등록)가 모두 끝났는지 확인 후 영업을
     시작하세요.
   - 사업자등록증ᆞ영업신고증 등은 영업장 내 게시가 필요할 수 있습니다."""

_INSURANCE_QUERIES = [
    "직장가입자 자격취득 신고 기한",
    "사업장가입자 자격취득 신고 기한",
    "고용보험 피보험자격 취득신고",
    "산재보험 보험관계 성립신고",
]


@tool
def get_opening_checklist() -> str:
    """오픈 준비(직원등록ᆞ영업시작) 체크리스트를 반환합니다.

    - "오픈 준비는 뭘 해야 하나요", "이제 마지막으로 뭐가 남았나요" 같은
      질문에 이 도구를 호출하세요. 인테리어ᆞ장비 설치는 여기가 아니라
      get_construction_guide(공사 단계)에서 다룹니다 - 사용자가 인테리어를
      물으면 이 도구 대신 그쪽을 호출하세요.
    - 영업 시작 항목은 법령 근거가 없는 순수 실무 체크리스트입니다 -
      [출처] 없이 안내된 그대로 전달하고, 없는 법적 근거를 지어내 붙이지
      마세요.
    - 직원 등록(4대보험) 항목만 법령에서 검색한 결과입니다(내부적으로
      국민연금법ᆞ국민건강보험법ᆞ고용보험법ᆞ고용산재보험료징수법을 각각
      검색해 합칩니다 - 직접 다시 search_regulations를 호출할 필요
      없습니다). 4개 법령의 신고 기한이 서로 다를 수 있으니 검색 결과에
      나온 대로만 전달하고 혼동하지 마세요.
    """
    logger.info("[도구] get_opening_checklist()")
    insurance_section = "1. 직원 등록(4대보험 가입) - 근로자를 채용하는 경우\n" + "\n\n".join(
        search_regulations.func(q) for q in _INSURANCE_QUERIES
    )
    return OPENING_CHECKLIST_STATIC + "\n\n" + insurance_section
