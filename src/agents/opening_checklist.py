"""Opening Checklist Agent - 오픈 준비(Step 4) 안내(부분 RAG 전환).

이 도메인은 항목 성격이 섞여 있어서 절반만 RAG로 바꿨다:
- 인테리어ᆞ장비설치ᆞ영업 시작: 법령 근거가 있는 게 아니라 순수 실무
  체크리스트다 - 애초에 검색할 법 조항이 없으므로 그대로 정적 텍스트로
  유지한다(RAG로 바꿀 대상 자체가 없음). 없는 근거를 [출처]로 지어내면
  안 되므로 이 항목들엔 인용을 안 붙인다.
- 직원 등록(4대보험 가입): 실제 신고 기한이 법령으로 정해진 행정 절차라
  RAG 전환 대상이다. 원래는 "법제처 찾기쉬운 생활법령정보"(2차 출처)
  원문 대조로 하드코딩했었는데, 2026-07-28에 국민연금법ᆞ국민건강보험법ᆞ
  고용보험법ᆞ고용산재보험료징수법(1차 출처) 원문을 새로 인덱싱한 뒤
  RAG로 검증하니 4개 법령의 신고 조항을 정확히 다 찾아내서(제8조ᆞ21조ᆞ
  15조ᆞ11조) 하드코딩 대신 검색으로 전환했다 - 2차 출처보다 1차 법령을
  직접 인용하는 게 더 정확하다.
"""
from __future__ import annotations

import logging

from langchain_core.tools import tool

from src.agents.regulation import search_regulations

logger = logging.getLogger(__name__)


OPENING_CHECKLIST_STATIC = """[오픈 준비 체크리스트]

아래는 일반적인 실무 절차 안내이며(법령 근거가 없는 순수 체크리스트),
실제 순서ᆞ방식은 업종ᆞ상황에 따라 달라질 수 있습니다.

1. 인테리어ᆞ시설 공사
   - 이미 안내받은 소방시설(설치 대상이 있다면)과 식품위생법상 영업 종류에
     맞는 주방ᆞ영업장 시설기준을 시공 단계에서 함께 반영하세요.
   - 간판ᆞ외부 광고물을 설치할 계획이면 별도 신고 대상 여부를 먼저
     확인하세요.

2. 장비ᆞ설비 설치
   - 주방기기ᆞ냉장/냉동 설비ᆞ포스(POS) 시스템 등 영업에 필요한 장비를
     설치하고 시운전하세요.
   - 소방시설 설치 대상이라면 설치 완료 후 소방서 점검ᆞ완비증명 절차가
     필요할 수 있습니다.

4. 영업 시작
   - 지금까지 안내받은 단계(건축 인허가ᆞ식품위생 영업신고ᆞ소방시설ᆞ
     사업자등록ᆞ위생교육ᆞ직원등록)가 모두 끝났는지 확인 후 영업을
     시작하세요.
   - 사업자등록증ᆞ영업신고증 등은 영업장 내 게시가 필요할 수 있습니다."""

_INSURANCE_QUERIES = [
    "직장가입자 자격취득 신고 기한",
    "사업장가입자 자격취득 신고 기한",
    "고용보험 피보험자격 취득신고",
    "산재보험 보험관계 성립신고",
]


@tool
def get_opening_checklist() -> str:
    """오픈 준비(인테리어ᆞ장비설치ᆞ직원등록ᆞ영업시작) 체크리스트를 반환합니다.

    - "오픈 준비는 뭘 해야 하나요", "이제 마지막으로 뭐가 남았나요" 같은
      질문에 이 도구를 호출하세요.
    - 인테리어ᆞ장비설치ᆞ영업시작 항목은 법령 근거가 없는 순수 실무
      체크리스트입니다 - [출처] 없이 안내된 그대로 전달하고, 없는 법적
      근거를 지어내 붙이지 마세요.
    - 직원 등록(4대보험) 항목만 법령에서 검색한 결과입니다(내부적으로
      국민연금법ᆞ국민건강보험법ᆞ고용보험법ᆞ고용산재보험료징수법을 각각
      검색해 합칩니다 - 직접 다시 search_regulations를 호출할 필요
      없습니다). 4개 법령의 신고 기한이 서로 다를 수 있으니 검색 결과에
      나온 대로만 전달하고 혼동하지 마세요.
    """
    logger.info("[도구] get_opening_checklist()")
    insurance_section = "3. 직원 등록(4대보험 가입) - 근로자를 채용하는 경우\n" + "\n\n".join(
        search_regulations.func(q) for q in _INSURANCE_QUERIES
    )
    return OPENING_CHECKLIST_STATIC + "\n\n" + insurance_section
