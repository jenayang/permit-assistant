from __future__ import annotations

import logging

from langchain_core.tools import tool

logger = logging.getLogger(__name__)


HYGIENE_EDUCATION_GUIDE = """[위생교육 안내]

1. 대상 및 교육시간
   카페ᆞ음식점 등 식품접객업(휴게음식점ᆞ일반음식점ᆞ제과점 등, 식품위생법
   시행령 제21조제8호)을 새로 시작하려는 사람은 영업신고 전 사전교육
   6시간을 이수해야 합니다.

2. 이수 시기
   원칙적으로 영업신고 전에 받아야 합니다. 다만 사전교육을 받기 곤란하다고
   허가관청ᆞ신고관청이 인정하는 경우에는 영업신고를 한 후 6개월 이내에
   이수해도 됩니다.

3. 교육 방법
   집합교육 또는 온라인(정보통신매체를 이용한 원격교육) 방법으로 받을 수
   있습니다. 실제 교육은 한국외식업중앙회 등 식품의약품안전처가 지정한
   교육기관에서 운영하며, 정확한 신청 방법ᆞ교육비는 관할 보건소나 해당
   교육기관에 확인하는 것을 권장합니다(협회별 세부 운영 방식은 바뀔 수
   있어 이 안내에서는 단정하지 않습니다).

[출처: 식품위생법 시행규칙 제52조ᆞ제54조]"""


@tool
def get_hygiene_education_guide() -> str:
    """식품위생교육(위생교육) 대상ᆞ교육시간ᆞ이수시기ᆞ교육방법 안내를 반환합니다.

    - 위생교육을 언제ᆞ몇 시간ᆞ어떻게 받아야 하는지 물으면 이 도구를
      호출하세요.
    - 법정 교육시간ᆞ이수시기ᆞ방법은 식품위생법 시행규칙 원문 대조를
      마친 확정 정보라 검색 없이 바로 반환합니다. 다만 실제 운영 기관명ᆞ
      교육비 같은 세부사항은 바뀔 수 있으니 안내문 그대로만 전달하고,
      정확한 확인은 관할 보건소를 권하세요 - 임의로 가격이나 기관을
      단정해서 덧붙이지 마세요.
    """
    logger.info("[도구] get_hygiene_education_guide()")
    return HYGIENE_EDUCATION_GUIDE
