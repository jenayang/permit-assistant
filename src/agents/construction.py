"""Construction Agent - 착공ᆞ설계ᆞ공사감리ᆞ사용승인 안내(RAG 기반, Step 2).

이 도메인이 통째로 빠져있던 걸 실사용 중 발견했다 - Step 3(창업 행정)에는
안내 도구가 있는데 Step 2(공사)에는 대응하는 도구가 아예 없어서, AI가
인허가 설명이 끝나면 공사 단계를 건너뛰고 바로 창업 준비 트랙으로
넘어가거나(사용자가 "공사는 왜 안 알려줘?"라고 지적해서야 알아챔), 근거
도구 없이 일반 지식으로 답을 지어내는 문제가 있었다(2026-07-27 세션
e854150e에서 재현). 처음엔 원문 대조한 정적 텍스트로 채웠는데, 2026-07-28
검증(RAG vs 정적 콘텐츠 비교)에서 RAG가 동일하거나 더 상세한 결론(착공신고
첨부서류 등)에 도달하는 걸 확인해서 하드코딩 대신 search_regulations로
전환했다.

"이 사례에 감리가 꼭 필요한지" 같은 세부 판정은 요건이 여러 겹(허가/신고
구분ᆞ규모ᆞ직영시공 여부 등)이라 규칙화하지 않고, 검색 결과 원칙+예외를
전달한 뒤 정확한 판정은 관할 구청 확인을 권하는 쪽을 유지한다(2026-07-27
논의, RAG 전환과 무관하게 그대로 적용).

인테리어ᆞ장비 설치는 원래 opening_checklist.py(오픈 준비, Step 4)에 있었는데,
실제로는 "시공"의 일부라 여기(공사, Step 2)로 옮겼다(2026-07-28 피드백).
법령 근거가 있는 착공신고ᆞ설계ᆞ감리ᆞ사용승인과 달리 순수 실무 체크리스트라
[출처] 없이 정적 텍스트로 붙인다 - RAG로 바꿀 대상 자체가 없다(검색할 조항이
없음).
"""
from __future__ import annotations

import logging

from langchain_core.tools import tool

from src.rag.regulation import search_regulations

logger = logging.getLogger(__name__)

_QUERIES = [
    "착공신고는 어떻게 하나요?",
    "건축사 설계 의무와 예외",
    "공사감리자 지정 기준",
    "사용승인을 받으려면 뭐가 필요한가요?",
]

# 법령 근거가 없는 순수 실무 체크리스트라 검색 없이 정적으로 붙인다
# (opening_checklist.py에서 이동, 2026-07-28).
_INTERIOR_NOTES = """[인테리어ᆞ장비 설치 - 실무 체크리스트, 법령 근거 없음]

- 이미 안내받은 소방시설(설치 대상이 있다면)과 식품위생법상 영업 종류에
  맞는 주방ᆞ영업장 시설기준을 시공 단계에서 함께 반영하세요.
- 간판ᆞ외부 광고물을 설치할 계획이면 별도 신고 대상 여부를 먼저 확인하세요.
- 주방기기ᆞ냉장/냉동 설비ᆞ포스(POS) 시스템 등 영업에 필요한 장비를 설치하고
  시운전하세요.
- 소방시설 설치 대상이라면 설치 완료 후 소방서 점검ᆞ완비증명 절차가 필요할
  수 있습니다."""


@tool
def get_construction_guide() -> str:
    """착공신고ᆞ설계ᆞ공사감리ᆞ사용승인ᆞ인테리어ᆞ장비설치(Step 2: 공사) 절차를 반환합니다.

    - 착공신고를 어떻게ᆞ언제 하는지, 건축사 설계ᆞ감리가 왜/언제 필요한지,
      사용승인을 어떻게 받는지, 인테리어ᆞ장비 설치는 어떻게 하는지 물으면
      이 도구를 호출하세요(내부적으로 건축법ᆞ시행령ᆞ시행규칙을 여러
      관점에서 검색 + 실무 체크리스트까지 합쳐서 돌려줍니다 - 직접 다시
      search_regulations를 호출할 필요 없습니다). 건축 인허가 판정
      ([Step 1-N])이 끝난 뒤에는 사용자가 따로 안 물어봐도 "다음은 공사
      단계"라는 걸 자연스럽게 짚어주면서 이 도구를 호출하세요 - Step 2를
      건너뛰고 바로 식품위생ᆞ사업자등록 등으로 넘어가면 안 됩니다.
    - **공사를 시작하기 전에 건축사사무소 선정이 필요한지부터 먼저
      짚어주세요** - 이 판정은 시스템이 매 턴 별도로 계산해 넣어주는
      "[건축사 설계 의무 판정]" 지시를 그대로 전달하세요(당신이 검색 결과의
      "건축사 설계 의무와 예외" 문구를 보고 다시 판단해 "규모에 따라
      필요할 수도 있다"처럼 흐리게 말하지 마세요 - 법적 의무 여부는 이미
      확정된 사실입니다). 이미 인허가 신청 때 건축사사무소를 통해 설계도서를
      준비했다면 그 사무소에 감리ᆞ착공신고까지 이어서 의뢰하는 게 일반적이라는
      것도 함께 안내하세요.
    - 인테리어ᆞ장비 설치 항목(체크리스트 마지막 부분)은 법령 근거가 없는
      순수 실무 안내입니다 - [출처] 없이 안내된 그대로 전달하고, 없는
      법적 근거를 지어내 붙이지 마세요.
    - "이 사례에 감리가 꼭 필요한지"처럼 세부 요건이 여러 겹으로 갈리는
      판단은 검색 결과만으로 단정하지 말고, 의무처럼 단정하지 말고 원칙+예외를
      전달한 뒤 관할 구청 확인을 권하세요.
    - **각 단계(착공신고ᆞ시공ᆞ감리ᆞ사용승인ᆞ인테리어) 안내 시 이 일을 누가
      하는지(건축사사무소 / 시공사ᆞ인테리어업체 / 건축주 본인) 구분해서
      안내하세요** - Step 1-3의 "[본인 준비]/[설계자 준비]" 표기와 같은 원칙.
    """
    logger.info("[도구] get_construction_guide()")
    legal_parts = "\n\n".join(search_regulations.func(q) for q in _QUERIES)
    return legal_parts + "\n\n" + _INTERIOR_NOTES
